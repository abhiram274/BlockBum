#pragma once

#include "blockbum/content/types.hpp"
#include "blockbum/content/content_store.hpp"
#include "blockbum/crypto/crypto_utils.hpp"
#include <string>
#include <vector>
#include <unordered_map>
#include <mutex>
#include <chrono>
#include <algorithm>
#include <optional>

namespace blockbum::content {

/// Storage Provider Reputation & Performance Record
struct StorageProviderStats {
    std::string provider_id;
    int32_t reputation_score{100}; // Starts at 100
    uint32_t total_challenges{0};
    uint32_t successful_challenges{0};
    uint32_t failed_challenges{0};
    uint64_t total_bytes_stored{0};
    bool is_quarantined{false};
};

/// Cryptographic Proof-of-Retrievability Challenge
struct StorageChallenge {
    std::string challenge_id;
    std::string chunk_cid;
    core::Hash256 challenge_salt{};
    std::string provider_id;
    uint64_t timestamp{0};
};

/// Cryptographic Proof generated by storage provider proving possession of uncorrupted chunk
struct StorageProof {
    std::string challenge_id;
    std::string chunk_cid;
    core::Hash256 proof_hash{}; // SHA-256(chunk_bytes || challenge_salt || provider_id)
};

/// Pinned storage lease with configurable expiration
struct StorageLease {
    std::string chunk_cid;
    std::string provider_id;
    std::string uploader_address;
    uint64_t size_bytes{0};
    uint64_t pinned_at{0};
    uint64_t expires_at{0};
};

/// Decentralized Storage Network Manager managing replication, availability challenges, and reputation
class StorageNetworkManager {
public:
    static constexpr uint64_t DEFAULT_LEASE_DURATION = 30 * 86400; // 30 days
    static constexpr uint64_t MAX_STORAGE_PER_UPLOADER = 500 * 1024 * 1024; // 500 MB quota
    static constexpr size_t MAX_CHUNK_SIZE_LIMIT = 2 * 1024 * 1024; // 2 MB max chunk size

    explicit StorageNetworkManager(std::shared_ptr<ContentStore> local_store)
        : store_(std::move(local_store)) {}

    /// Register or update a storage provider
    void register_provider(const std::string& provider_id) {
        std::lock_guard<std::mutex> lock(mutex_);
        if (providers_.find(provider_id) == providers_.end()) {
            StorageProviderStats stats;
            stats.provider_id = provider_id;
            stats.reputation_score = 100;
            providers_[provider_id] = stats;
        }
    }

    /// Pin chunk with lease expiration and uploader quota check (DoS prevention)
    bool pin_chunk(const std::string& chunk_cid,
                   const std::string& provider_id,
                   const std::string& uploader_address,
                   uint64_t size_bytes,
                   uint64_t current_time = 0,
                   uint64_t lease_duration = DEFAULT_LEASE_DURATION) {
        std::lock_guard<std::mutex> lock(mutex_);

        if (size_bytes > MAX_CHUNK_SIZE_LIMIT) {
            return false; // Chunk exceeds maximum chunk size limit
        }

        uint64_t current_uploader_bytes = uploader_usage_[uploader_address];
        if (current_uploader_bytes + size_bytes > MAX_STORAGE_PER_UPLOADER) {
            return false; // Quota exceeded
        }

        uint64_t now = (current_time != 0) ? current_time : 1700000000;
        StorageLease lease;
        lease.chunk_cid = chunk_cid;
        lease.provider_id = provider_id;
        lease.uploader_address = uploader_address;
        lease.size_bytes = size_bytes;
        lease.pinned_at = now;
        lease.expires_at = now + lease_duration;

        leases_[chunk_cid] = lease;
        uploader_usage_[uploader_address] += size_bytes;
        providers_[provider_id].total_bytes_stored += size_bytes;
        return true;
    }

    /// Generate an availability verification challenge for a provider storing a chunk
    StorageChallenge generate_challenge(const std::string& chunk_cid,
                                        const std::string& provider_id,
                                        uint64_t current_time = 0) {
        std::lock_guard<std::mutex> lock(mutex_);
        uint64_t now = (current_time != 0) ? current_time : 1700000000;

        StorageChallenge challenge;
        challenge.challenge_id = "ch_" + chunk_cid.substr(0, 16) + "_" + std::to_string(++challenge_counter_);
        challenge.chunk_cid = chunk_cid;
        challenge.provider_id = provider_id;
        challenge.timestamp = now;

        // Challenge salt derived from counter and time
        std::string salt_str = challenge.challenge_id + ":" + std::to_string(now);
        challenge.challenge_salt = crypto::CryptoUtils::sha256(
            std::span<const uint8_t>(reinterpret_cast<const uint8_t*>(salt_str.data()), salt_str.size()));

        pending_challenges_[challenge.challenge_id] = challenge;
        return challenge;
    }

    /// Provider computes proof of possession
    static StorageProof compute_proof(const StorageChallenge& challenge,
                                      std::span<const uint8_t> chunk_bytes) {
        std::vector<uint8_t> proof_input;
        proof_input.reserve(chunk_bytes.size() + 32 + challenge.provider_id.size());
        proof_input.insert(proof_input.end(), chunk_bytes.begin(), chunk_bytes.end());
        proof_input.insert(proof_input.end(), challenge.challenge_salt.begin(), challenge.challenge_salt.end());
        proof_input.insert(proof_input.end(), challenge.provider_id.begin(), challenge.provider_id.end());

        StorageProof proof;
        proof.challenge_id = challenge.challenge_id;
        proof.chunk_cid = challenge.chunk_cid;
        proof.proof_hash = crypto::CryptoUtils::sha256(proof_input);
        return proof;
    }

    /// Verify proof submitted by provider and update reputation score
    bool verify_and_score_proof(const StorageProof& proof,
                                std::span<const uint8_t> ground_truth_chunk_bytes) {
        std::lock_guard<std::mutex> lock(mutex_);
        auto it = pending_challenges_.find(proof.challenge_id);
        if (it == pending_challenges_.end()) {
            return false; // Unknown or expired challenge
        }

        const auto& ch = it->second;
        auto expected_proof = compute_proof(ch, ground_truth_chunk_bytes);

        auto& provider = providers_[ch.provider_id];
        provider.total_challenges++;

        if (proof.proof_hash == expected_proof.proof_hash) {
            // Success: +5 reputation
            provider.successful_challenges++;
            provider.reputation_score = (std::min)(200, provider.reputation_score + 5);
            pending_challenges_.erase(it);
            return true;
        } else {
            // Failure: -30 penalty
            provider.failed_challenges++;
            provider.reputation_score = (std::max)(0, provider.reputation_score - 30);
            if (provider.reputation_score < 40) {
                provider.is_quarantined = true;
            }
            pending_challenges_.erase(it);
            return false;
        }
    }

    /// Record challenge failure when provider times out
    void record_challenge_timeout(const std::string& challenge_id) {
        std::lock_guard<std::mutex> lock(mutex_);
        auto it = pending_challenges_.find(challenge_id);
        if (it == pending_challenges_.end()) return;

        auto& provider = providers_[it->second.provider_id];
        provider.total_challenges++;
        provider.failed_challenges++;
        provider.reputation_score = (std::max)(0, provider.reputation_score - 25);
        if (provider.reputation_score < 40) {
            provider.is_quarantined = true;
        }
        pending_challenges_.erase(it);
    }

    /// Evict expired storage leases and free uploader quota
    size_t evict_expired_leases(uint64_t current_time) {
        std::lock_guard<std::mutex> lock(mutex_);
        size_t evicted = 0;
        for (auto it = leases_.begin(); it != leases_.end(); ) {
            if (it->second.expires_at <= current_time) {
                if (uploader_usage_[it->second.uploader_address] >= it->second.size_bytes) {
                    uploader_usage_[it->second.uploader_address] -= it->second.size_bytes;
                } else {
                    uploader_usage_[it->second.uploader_address] = 0;
                }
                providers_[it->second.provider_id].total_bytes_stored -= it->second.size_bytes;
                it = leases_.erase(it);
                evicted++;
            } else {
                ++it;
            }
        }
        return evicted;
    }

    [[nodiscard]] std::optional<StorageProviderStats> get_provider_stats(const std::string& provider_id) const {
        std::lock_guard<std::mutex> lock(mutex_);
        auto it = providers_.find(provider_id);
        if (it != providers_.end()) return it->second;
        return std::nullopt;
    }

    [[nodiscard]] uint64_t get_uploader_usage(const std::string& uploader_address) const {
        std::lock_guard<std::mutex> lock(mutex_);
        auto it = uploader_usage_.find(uploader_address);
        if (it != uploader_usage_.end()) return it->second;
        return 0;
    }

    [[nodiscard]] bool is_chunk_pinned(const std::string& chunk_cid) const {
        std::lock_guard<std::mutex> lock(mutex_);
        return leases_.find(chunk_cid) != leases_.end();
    }

private:
    mutable std::mutex mutex_;
    std::shared_ptr<ContentStore> store_;
    uint64_t challenge_counter_{0};

    std::unordered_map<std::string, StorageProviderStats> providers_;
    std::unordered_map<std::string, StorageChallenge> pending_challenges_;
    std::unordered_map<std::string, StorageLease> leases_;
    std::unordered_map<std::string, uint64_t> uploader_usage_;
};

} // namespace blockbum::content
