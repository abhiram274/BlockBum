#include <gtest/gtest.h>
#include "blockbum/crypto/standard_crypto.hpp"
#include "blockbum/crypto/wallet.hpp"
#include <filesystem>

using namespace blockbum;

class WalletAndIdentityTest : public ::testing::Test {
protected:
    void SetUp() override {
        test_dir_ = std::filesystem::temp_directory_path() / "blockbum_wallet_tests";
        std::filesystem::remove_all(test_dir_);
        crypto_engine_ = std::make_shared<crypto::StandardCryptoEngine>();
    }

    void TearDown() override {
        std::filesystem::remove_all(test_dir_);
    }

    std::filesystem::path test_dir_;
    std::shared_ptr<crypto::StandardCryptoEngine> crypto_engine_;
};

TEST_F(WalletAndIdentityTest, KeypairGenerationAndSignatureVerification) {
    auto kp = crypto_engine_->generate_keypair();

    std::string message = "BlockBum Identity Verification Payload";
    std::span<const uint8_t> msg_span(reinterpret_cast<const uint8_t*>(message.data()), message.size());

    auto signature = crypto_engine_->sign(msg_span, kp.secret_key);

    // Signature must be valid
    EXPECT_TRUE(crypto_engine_->verify(msg_span, signature, kp.public_key));

    // Tampered message must fail verification
    std::string tampered_message = "BlockBum Identity Verification Tampered!";
    std::span<const uint8_t> tampered_span(reinterpret_cast<const uint8_t*>(tampered_message.data()), tampered_message.size());
    EXPECT_FALSE(crypto_engine_->verify(tampered_span, signature, kp.public_key));
}

TEST_F(WalletAndIdentityTest, RejectsCorruptedSignatureAndCorruptedKeys) {
    auto kp = crypto_engine_->generate_keypair();
    std::string msg = "Test message";
    std::span<const uint8_t> msg_span(reinterpret_cast<const uint8_t*>(msg.data()), msg.size());

    // 1. All-zero signature
    crypto::Signature zero_sig{};
    EXPECT_FALSE(crypto_engine_->verify(msg_span, zero_sig, kp.public_key));

    // 2. All-zero public key
    auto sig = crypto_engine_->sign(msg_span, kp.secret_key);
    crypto::PublicKey zero_pub{};
    EXPECT_FALSE(crypto_engine_->verify(msg_span, sig, zero_pub));

    // 3. Signature where R == s
    crypto::Signature bad_sig{};
    bad_sig.fill(0x42);
    EXPECT_FALSE(crypto_engine_->verify(msg_span, bad_sig, kp.public_key));
}

TEST_F(WalletAndIdentityTest, WalletIdentityManagementAndLocalPersistence) {
    {
        crypto::Wallet wallet(test_dir_, crypto_engine_);
        auto id1 = wallet.create_identity("alice");
        auto id2 = wallet.create_identity("bob");

        EXPECT_EQ(id1.alias(), "alice");
        EXPECT_EQ(id2.alias(), "bob");
        EXPECT_NE(id1.address(), id2.address());

        auto list = wallet.list_identities();
        EXPECT_EQ(list.size(), 2);
    }

    // Reopen wallet from disk
    crypto::Wallet reopened_wallet(test_dir_, crypto_engine_);
    auto list = reopened_wallet.list_identities();
    EXPECT_EQ(list.size(), 2);

    auto alice_opt = reopened_wallet.get_identity("alice");
    ASSERT_TRUE(alice_opt.has_value());
    EXPECT_EQ(alice_opt->alias(), "alice");
}

TEST_F(WalletAndIdentityTest, IdentityExportAndRecovery) {
    crypto::Wallet wallet(test_dir_, crypto_engine_);
    auto original = wallet.create_identity("creator");
    std::string recovery_phrase = original.export_recovery_phrase();
    EXPECT_FALSE(recovery_phrase.empty());

    // Recover identity under a new alias
    auto recovered = wallet.recover_identity("recovered_creator", recovery_phrase);
    EXPECT_EQ(recovered.address(), original.address());
    EXPECT_EQ(recovered.public_key(), original.public_key());
}

TEST_F(WalletAndIdentityTest, TransactionSigningAndVerification) {
    crypto::Wallet wallet(test_dir_, crypto_engine_);
    auto alice = wallet.create_identity("alice");

    core::Transaction tx;
    tx.version = 1;
    tx.recipient = "community_feed";
    tx.nonce = 1;
    std::string payload = "Encrypted community post";
    tx.payload = std::vector<uint8_t>(payload.begin(), payload.end());

    // Sign transaction with alice
    ASSERT_TRUE(wallet.sign_transaction(tx, "alice"));
    EXPECT_EQ(tx.sender, alice.address());
    EXPECT_EQ(tx.sender_pubkey, alice.public_key());

    // Verify valid transaction
    EXPECT_TRUE(wallet.verify_transaction(tx));

    // Tampered payload must fail verification
    tx.payload.push_back(0xFF);
    EXPECT_FALSE(wallet.verify_transaction(tx));
}

TEST_F(WalletAndIdentityTest, UnauthorizedTransactionFails) {
    crypto::Wallet wallet(test_dir_, crypto_engine_);
    auto alice = wallet.create_identity("alice");
    auto bob = wallet.create_identity("bob");

    core::Transaction tx;
    tx.recipient = "treasury";
    ASSERT_TRUE(wallet.sign_transaction(tx, "alice"));

    // Impersonate sender without valid signature
    tx.sender = bob.address();
    tx.sender_pubkey = bob.public_key(); // But signature was generated by alice!

    EXPECT_FALSE(wallet.verify_transaction(tx));
}
